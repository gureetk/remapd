#!/usr/bin/env python3
"""Regenerates daemon/keynames.h (Linux key names) from the kernel headers.

    python3 tools/gen_keynames.py [/usr/include/linux/input-event-codes.h]
"""
import os
import re
import sys

header = sys.argv[1] if len(sys.argv) > 1 else "/usr/include/linux/input-event-codes.h"
src = open(header).read()
defs, order = {}, []
for m in re.finditer(r"^#define\s+((?:KEY|BTN)_[A-Z0-9_]+)\s+(\S+)", src, re.M):
    defs[m.group(1)] = m.group(2)
    order.append(m.group(1))


def resolve(value, depth=0):
    try:
        return int(value, 0)
    except ValueError:
        return resolve(defs[value], depth + 1) if value in defs and depth < 5 else None


skip = {"KEY_MAX", "KEY_CNT", "KEY_MIN_INTERESTING"}
rows = [(n, resolve(defs[n])) for n in order if n not in skip]
rows = [(n, v) for n, v in rows if v is not None and v <= 0x2ff]

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "daemon", "keynames.h")
with open(path, "w") as f:
    f.write("/* Linux key names. Generated by tools/gen_keynames.py from\n"
            " * linux/input-event-codes.h; don't edit. */\n")
    f.write("static const struct keyname { const char *name; unsigned short code; } keynames[] = {\n")
    for name, value in rows:
        f.write('\t{ "%s", %d },\n' % (name, value))
    f.write("};\n")
print(len(rows), "Linux key names written to", os.path.normpath(path))
