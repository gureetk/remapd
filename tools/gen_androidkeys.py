#!/usr/bin/env python3
"""Regenerates daemon/androidkeys.h (Android key names) from the Android SDK.

    python3 tools/gen_androidkeys.py $ANDROID_HOME/platforms/android-<N>/android.jar

Reads the KEYCODE_* constants of android.view.KeyEvent with `javap`.
"""
import os
import re
import subprocess
import sys

if len(sys.argv) != 2:
    sys.exit(__doc__)
out = subprocess.run(["javap", "-constants", "-classpath", sys.argv[1], "android.view.KeyEvent"],
                     capture_output=True, text=True, check=True).stdout
keys = re.findall(r"public static final int KEYCODE_([A-Z0-9_]+) = (\d+);", out)
if not keys:
    sys.exit("no KEYCODE_ constants found")

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "daemon", "androidkeys.h")
with open(path, "w") as f:
    f.write("/* Android key names (KeyEvent.KEYCODE_* without the prefix).\n"
            " * Generated by tools/gen_androidkeys.py from the Android SDK; don't edit. */\n")
    f.write("static const struct androidkey { const char *name; unsigned short code; } androidkeys[] = {\n")
    for name, value in keys:
        f.write('\t{ "%s", %s },\n' % (name, value))
    f.write("};\n")
print(len(keys), "Android keys written to", os.path.normpath(path))
